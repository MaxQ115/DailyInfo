const LIQUOR_CACHE_KEY = 'dailyinfo_liquor_cache_v1';

const LIQUOR_SHORT_NAMES = {
  1: '飞天茅台',
  10: '精品茅台',
  11: '茅台1935',
  2: '五粮液普五',
  12: '五粮液1618',
  7: '青花汾20',
  3: '国窖1573',
  4: '梦之蓝M6+',
  9: '古井贡古20',
  6: '习酒君品',
  8: '青花郎',
  5: '水晶剑南春'
};

function loadLiquorStore() {
  const baseList = Array.isArray(window.PRESET_LIQUOR_LIST) ? JSON.parse(JSON.stringify(window.PRESET_LIQUOR_LIST)) : [];
  const baseDetails = window.PRESET_LIQUOR_DETAILS ? JSON.parse(JSON.stringify(window.PRESET_LIQUOR_DETAILS)) : {};

  try {
    const raw = localStorage.getItem(LIQUOR_CACHE_KEY);
    if (raw) {
      const cached = JSON.parse(raw);
      if (Array.isArray(cached.list) && cached.list.length > 0) {
        const baseLatestDate = baseList[0]?.price_date || '';
        const cacheLatestDate = cached.list[0]?.price_date || '';
        if (cacheLatestDate >= baseLatestDate) {
          baseList.splice(0, baseList.length, ...cached.list);
        }
      }
      if (cached.details && typeof cached.details === 'object') {
        Object.keys(cached.details).forEach(pid => {
          if (!baseDetails[pid]) {
            baseDetails[pid] = cached.details[pid];
          } else {
            // 合并历史日期记录并按时间倒序去重
            const histMap = new Map();
            (baseDetails[pid].history || []).forEach(h => histMap.set(h.date, h));
            (cached.details[pid].history || []).forEach(h => histMap.set(h.date, h));
            const mergedHist = Array.from(histMap.values()).sort((a, b) => b.date.localeCompare(a.date));
            baseDetails[pid].history = mergedHist;
            if (cached.details[pid].detail) {
              baseDetails[pid].detail = { ...baseDetails[pid].detail, ...cached.details[pid].detail };
            }
          }
        });
      }
    }
  } catch (e) {
    console.warn('读取酒价内参本地缓存异常:', e);
  }

  return { list: baseList, details: baseDetails };
}

function saveLiquorStore(store) {
  try {
    localStorage.setItem(LIQUOR_CACHE_KEY, JSON.stringify({
      updatedAt: Date.now(),
      list: store.list,
      details: store.details
    }));
  } catch (e) {
    console.warn('保存酒价内参缓存失败:', e);
  }
}

/**
 * 将所有知名白酒大单品的历史与最新价格展开为按【时间倒序】排列的扁平记录流
 * 每条记录包含：date (时间), name (酒), price (酒价), price_change (较前日涨跌), specifications, unit, pic
 */
function buildLiquorTimelineRows(store) {
  const list = store?.list || [];
  const details = store?.details || {};
  const metaMap = new Map();

  list.forEach((item, idx) => {
    const pid = String(item.liquor_id);
    metaMap.set(pid, {
      liquor_id: item.liquor_id,
      name: (item.name || '').trim(),
      shortName: LIQUOR_SHORT_NAMES[item.liquor_id] || (item.name || '').trim(),
      pic: item.pic || '',
      specifications: item.specifications || '500ml',
      unit: item.unit || '元/瓶',
      sort: item.sort || (idx + 1),
      latestPrice: item.price,
      latestChange: item.price_change,
      latestDate: item.price_date
    });
  });

  const rows = [];
  const seenKeys = new Set();

  // 1. 先从各单品的 history 中提取每日成交终端零售价
  Object.keys(details).forEach(pid => {
    const detObj = details[pid];
    const detailInfo = detObj?.detail || {};
    const meta = metaMap.get(String(pid)) || {
      liquor_id: Number(pid),
      name: (detailInfo.name || '').trim(),
      shortName: LIQUOR_SHORT_NAMES[pid] || (detailInfo.name || '').trim(),
      pic: detailInfo.pic || '',
      specifications: detailInfo.specifications || '500ml',
      unit: detailInfo.unit || '元/瓶',
      sort: detailInfo.sort || 99
    };

    const historyArr = Array.isArray(detObj?.history) ? detObj.history : [];
    historyArr.forEach(h => {
      if (!h || !h.date || h.price == null) return;
      const uKey = `${h.date}_${meta.liquor_id}`;
      if (seenKeys.has(uKey)) return;
      seenKeys.add(uKey);
      rows.push({
        id: uKey,
        date: h.date,
        liquor_id: meta.liquor_id,
        name: meta.name,
        shortName: meta.shortName,
        pic: meta.pic,
        specifications: meta.specifications,
        price: Number(h.price),
        price_change: Number(h.price_change || 0),
        unit: h.unit || meta.unit || '元/瓶',
        sort: meta.sort
      });
    });
  });

  // 2. 补充 list 中可能尚未合入 history 的最新一日数据
  list.forEach(item => {
    if (!item || !item.price_date || item.price == null) return;
    const meta = metaMap.get(String(item.liquor_id));
    const uKey = `${item.price_date}_${item.liquor_id}`;
    if (!seenKeys.has(uKey) && meta) {
      seenKeys.add(uKey);
      rows.push({
        id: uKey,
        date: item.price_date,
        liquor_id: meta.liquor_id,
        name: meta.name,
        shortName: meta.shortName,
        pic: meta.pic,
        specifications: meta.specifications,
        price: Number(item.price),
        price_change: Number(item.price_change || 0),
        unit: item.unit || '元/瓶',
        sort: meta.sort
      });
    }
  });

  // 严格按时间倒序排列（最新日期在前；同一日期内按名酒排序权重排列）
  rows.sort((a, b) => {
    const dateCmp = b.date.localeCompare(a.date);
    if (dateCmp !== 0) return dateCmp;
    return (a.sort || 99) - (b.sort || 99);
  });

  return rows;
}

/**
 * 通过 JSONP 从新浪财经【酒价内参】官方接口拉取最新酒价列表
 */
function fetchSinaLiquorListJsonp(timeoutMs = 8000) {
  return new Promise((resolve, reject) => {
    const cbName = 'sina_liquor_list_cb_' + Math.floor(Math.random() * 1000000);
    let settled = false;

    const script = document.createElement('script');
    const cleanup = () => {
      settled = true;
      try { delete window[cbName]; } catch (e) { window[cbName] = undefined; }
      if (script.parentNode) script.parentNode.removeChild(script);
    };

    const timer = setTimeout(() => {
      if (!settled) {
        cleanup();
        reject(new Error('拉取新浪酒价内参列表超时'));
      }
    }, timeoutMs);

    window[cbName] = function(res) {
      if (settled) return;
      clearTimeout(timer);
      cleanup();
      const list = res?.result?.data?.list;
      if (Array.isArray(list) && list.length > 0) {
        resolve(list);
      } else {
        reject(new Error('新浪酒价内参列表返回格式异常'));
      }
    };

    script.src = `https://business.cj.sina.cn/api/liquor_price/list?callback=${cbName}&_t=${Date.now()}`;
    script.onerror = () => {
      if (!settled) {
        clearTimeout(timer);
        cleanup();
        reject(new Error('新浪酒价内参列表网络请求失败'));
      }
    };
    document.head.appendChild(script);
  });
}

